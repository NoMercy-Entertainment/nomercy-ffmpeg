"""Generate the unit-test fixtures of nm_lyricsalign_phones.h from espeak-ng's CLI and the model vocabulary:

    python -I tools/lyricsalign-lab/make_phone_fixture.py <espeak-ng executable> <vocab.json>

Writes tests/unit/fixtures/lyricsalign-vocab.txt (the 392 vocabulary strings in id order),
tests/unit/fixtures/lyricsalign-phones.tsv (phone<TAB>expected id or -1, every distinct phone espeak-ng 1.52.0 gives
for a short corpus in twelve voices plus hand cases) and tests/unit/fixtures/jfk/jfk-ipa.txt (the raw
`--ipa --sep=_` output for the JFK sentence).

The expected ids are the prototype's (lyrics_eval.phonemes._candidates, reimplemented here): the phone itself, the
nearest-neighbour table, NFD with Mn/Cf dropped, that without the length mark, its first character; first hit wins.
"""
import json
import re
import subprocess
import sys
import unicodedata
from pathlib import Path

root = Path(__file__).resolve().parents[2]
fixtures = root / "tests" / "unit" / "fixtures"

STRESS = str.maketrans("", "", "ˈˌ")
LANGUAGE_SWITCH = re.compile(r"\([a-z]{2,3}(-[a-z]+)?\)")
NEAREST = {"ʏ": "ʊ", "ɒ": "ɔ", "ɵ": "ø", "ʉ": "u", "ɨ": "ɪ", "ɫ": "l", "ɱ": "m", "ʌʊ": "aʊ", "œy": "ɔø"}

JFK = "And so my fellow Americans, ask not what your country can do for you, ask what you can do for your country."

CORPUS = {
    "en-us": [JFK, "The quick brown fox jumps over the lazy dog.", "I'm a stranger here myself, she said.",
              "Yesterday all my troubles seemed so far away.", "Hello darkness my old friend, I've come to talk with you again."],
    "en-gb": ["Water the garden before the sun comes up.", "Nothing compares to you.", "We're going to Bath on Thursday."],
    "nl": ["Ik hou van jou en jij van mij.", "Het is een nacht die je normaal alleen in films ziet.",
           "Huis, tuin, muis, uit, oud, blauw, koud.", "Zij zei: morgen komt het goed."],
    "de": ["Über den Wolken muss die Freiheit wohl grenzenlos sein.", "Ich möchte ein Eisbär sein im kalten Polar.",
           "Größe, Mädchen, Bäume, Öl."],
    "fr": ["Non, rien de rien, non, je ne regrette rien.", "Un, deux, trois, nous irons au bois.",
           "Les enfants chantent dans le jardin."],
    "es": ["Despacito, quiero respirar tu cuello despacito.", "La niña canta en la plaza.", "Año, España, mañana."],
    "it": ["Nel blu dipinto di blu, felice di stare lassù.", "Gli gnocchi sono buonissimi."],
    "pt": ["Garota de Ipanema, coisa mais linda.", "Não, não sei, coração."],
    "ja": ["こんにちは、世界。", "さくら さくら やよいの そらは"],
    "ru": ["Подмосковные вечера.", "Я тебя люблю."],
    "pl": ["Szła dzieweczka do laseczka.", "Źdźbło, chrząszcz brzmi w trzcinie."],
    "sv": ["Hej, hur mår du idag?", "Små grodorna, små grodorna är lustiga att se."],
}

HAND_CASES = [*NEAREST.keys(), "ɛ̃", "ãː", "ʰ", "ɔːɹ", "oʊ", "̃", "ʲ", "t̪", "ɹ̩", "aɪ", "eɪ̯", "ɚ", "ɝ"]


def espeak(exe: str, voice: str, text: str) -> str:
    return subprocess.run([exe, "-q", "--ipa", "--sep=_", "-v", voice, "--stdin"], input=text + "\n",
                          capture_output=True, text=True, encoding="utf-8", check=True).stdout


def parse_ipa(output: str) -> list[list[str]]:
    words = []
    for word in LANGUAGE_SWITCH.sub("", output).split():
        phones = [p.translate(STRESS) for p in word.split("_")]
        phones = [p for p in phones if p]
        if phones:
            words.append(phones)
    return words


def candidates(phone: str) -> list[str]:
    plain = "".join(c for c in unicodedata.normalize("NFD", phone) if unicodedata.category(c) not in ("Mn", "Cf"))
    return [phone, NEAREST.get(phone, phone), plain, plain.replace("ː", ""), plain[:1]]


def main(exe: str, vocab_path: str) -> None:
    vocab_map = json.loads(Path(vocab_path).read_text(encoding="utf-8"))
    vocab = [None] * len(vocab_map)
    for tok, idx in vocab_map.items():
        vocab[idx] = tok
    (fixtures / "lyricsalign-vocab.txt").write_text("\n".join(vocab) + "\n", encoding="utf-8", newline="\n")

    phones: dict[str, int] = {}
    per_voice = {}
    for voice, texts in CORPUS.items():
        n = 0
        for text in texts:
            for word in parse_ipa(espeak(exe, voice, text)):
                for p in word:
                    n += 1
                    if p not in phones:
                        phones[p] = next((vocab_map[c] for c in candidates(p) if c in vocab_map), -1)
        per_voice[voice] = n
    for p in HAND_CASES:
        phones.setdefault(p, next((vocab_map[c] for c in candidates(p) if c in vocab_map), -1))

    rows = sorted(phones.items())
    with (fixtures / "lyricsalign-phones.tsv").open("w", encoding="utf-8", newline="\n") as f:
        f.write("# phone\texpected vocabulary id (-1 = no candidate hits); generated by tools/lyricsalign-lab/make_phone_fixture.py\n")
        for p, i in rows:
            f.write(f"{p}\t{i}\n")
    raw = espeak(exe, "en-us", JFK)
    (fixtures / "jfk" / "jfk-ipa.txt").write_text(raw, encoding="utf-8", newline="\n")
    misses = sum(1 for _, i in rows if i < 0)
    print(f"{len(rows)} distinct phones ({misses} with no candidate), per voice: {per_voice}", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        sys.exit(2)
    main(sys.argv[1], sys.argv[2])

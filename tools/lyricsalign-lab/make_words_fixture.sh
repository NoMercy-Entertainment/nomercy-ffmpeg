#!/bin/bash
# Generate tests/unit/fixtures/lyricsalign-words.tsv, the fixture of the
# word tie (nm_lp_tie in scripts/includes/nm_lyricsalign_phones.h, #131):
# lines and their whitespace tokens as espeak-ng phonemizes them, each next to
# the words[] entries the tie must make of them.
#
# Runs inside the lab, after `run.sh build` has built espeak-ng once:
#
#   tools/lyricsalign-lab/run.sh shell /repo/tools/lyricsalign-lab/make_words_fixture.sh
#
# The phones come from the library the filter links (espeak-check.c asks for
# them the way the filter does), so the fixture is what the filter sees. The
# expected entries in the table below are written by hand: they are the
# behaviour #131 asks for, not a copy of what the code happens to do.
#
# The lines are made up for this file; none is a lyric.
set -euo pipefail
set -f   # the tokens are split on blanks below; none is a file pattern

PREFIX=${PREFIX:-/opt/nm}
DATA=${PREFIX}/share/espeak-ng-data
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${HERE}/../../tests/unit/fixtures/lyricsalign-words.tsv"

[[ -f ${PREFIX}/lib/libespeak-ng.a && -f ${DATA}/phontab ]] || { echo "no espeak-ng in ${PREFIX}; run build.sh first" >&2; exit 1; }
gcc -O1 "${HERE}/espeak-check.c" -I"${PREFIX}/include" -L"${PREFIX}/lib" -lespeak-ng -lucd -lm -o /tmp/espeak-check

# voice | line | the entries: label:phones, " | " between them
table='
en-us|of the people|of:2 | the:2 | people:4
en-us|I was in the house|I:1 | was:3 | in:2 | the:2 | house:3
en-us|at the end of the day|at:2 | the:2 | end:3 | of:2 | the:2 | day:2
en-us|back in the summer of 1999|back:3 | in:2 | the:2 | summer:5 | of:2 | 1999:21
en-us|I want to be free|I:1 | want:4 | to be:4 | free:3
en-us|to the left of a man|to:2 | the:2 | left:4 | of a:3 | man:3
en-us|out of the blue and into the black|out of:4 | the:2 | blue:3 | and:3 | into:4 | the:2 | black:4
en-us|ask not - what your country can do for you 1999|ask:3 | not:3 | what:3 | your:2 | country:6 | can:3 | do:2 | for:2 | you:2 | 1999:21
en-us|we don'"'"'t need no education|we:2 | don'"'"'t:4 | need:3 | no:2 | education:8
nl|ik zit in de trein naar huis|ik:2 | zit:3 | in:2 | de:2 | trein:4 | naar:3 | huis:3
de|wir sind in dem Haus am See|wir:3 | sind:4 | in:2 | dem:3 | Haus:3 | am:2 | See:2
'

{
	echo "# Lines and their whitespace tokens as espeak-ng $(grep -m1 -o 'Version: .*' "${PREFIX}/lib/pkgconfig/espeak-ng.pc" | cut -d' ' -f2) phonemizes them (the library, IPA, '_' between phones),"
	echo "# and the words[] entries nm_lp_tie() must make of each line: label:phones, \" | \" between entries."
	echo "# Generated by tools/lyricsalign-lab/make_words_fixture.sh; the entries are written by hand in its table."
	echo "# LINE <voice> <text> <entries> <ipa of the line>, then one TOK <token> <ipa of the token alone> per token."
	while IFS='|' read -r voice text want; do
		[[ -n "${voice}" ]] || continue
		want="${want# }"
		printf 'LINE\t%s\t%s\t%s\t%s\n' "${voice}" "${text}" "${want}" "$(/tmp/espeak-check "${DATA}" "${voice}" "${text}")"
		for tok in ${text}; do
			printf 'TOK\t%s\t%s\n' "${tok}" "$(/tmp/espeak-check "${DATA}" "${voice}" "${tok}")"
		done
	done <<<"${table}"
} >"${OUT}"
echo "wrote ${OUT}: $(grep -c '^LINE' "${OUT}") lines, $(grep -c '^TOK' "${OUT}") tokens"

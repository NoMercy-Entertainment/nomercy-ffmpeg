"""Generate scripts/includes/nm_lyricsalign_unicode.inc: the Unicode facts nm_lyricsalign_phones.h needs for the
prototype's third mapping candidate (unicodedata.normalize("NFD", phone) with categories Mn and Cf dropped).

    python -I tools/lyricsalign-lab/make_unicode_inc.py

Two tables, from this interpreter's unicodedata (Python 3.12, Unicode 15.0):
  - NM_LP_DECOMP: code point -> the base code points of its canonical decomposition with Mn/Cf removed, for the
    precomposed Latin letters U+00C0-U+024F and U+1E00-U+1EFF (what espeak-ng's IPA can contain);
  - NM_LP_MARKS: the [lo, hi] ranges of code points whose category is Mn or Cf, over U+0000-U+FFFF.
"""
import sys
import unicodedata
from pathlib import Path

out = Path(__file__).resolve().parents[2] / "scripts" / "includes" / "nm_lyricsalign_unicode.inc"


def stripped(cp: int) -> list[int]:
    return [ord(c) for c in unicodedata.normalize("NFD", chr(cp)) if unicodedata.category(c) not in ("Mn", "Cf")]


decomp = []
for lo, hi in ((0x00C0, 0x024F), (0x1E00, 0x1EFF)):
    for cp in range(lo, hi + 1):
        base = stripped(cp)
        if base != [cp]:
            assert 1 <= len(base) <= 2, (hex(cp), base)
            decomp.append((cp, base))

ranges = []
start = None
for cp in range(0x10000):
    is_mark = unicodedata.category(chr(cp)) in ("Mn", "Cf")
    if is_mark and start is None:
        start = cp
    elif not is_mark and start is not None:
        ranges.append((start, cp - 1))
        start = None
if start is not None:
    ranges.append((start, 0xFFFF))

lines = [
    f"/* Generated by tools/lyricsalign-lab/make_unicode_inc.py (Python {sys.version.split()[0]}, "
    f"Unicode {unicodedata.unidata_version}); do not edit. */",
    "",
    "/* Precomposed Latin letters -> base code points (NFD with Mn/Cf dropped); 0 = none. */",
    "static const struct { uint16_t cp; uint16_t base[2]; } nm_lp_decomp[] = {",
]
lines += [f"    {{ 0x{cp:04X}, {{ 0x{b[0]:04X}, 0x{(b[1] if len(b) > 1 else 0):04X} }} }}," for cp, b in decomp]
lines += [
    "};",
    "",
    "/* Code point ranges of category Mn (nonspacing mark) and Cf (format), U+0000-U+FFFF. */",
    "static const struct { uint16_t lo, hi; } nm_lp_marks[] = {",
]
lines += [f"    {{ 0x{lo:04X}, 0x{hi:04X} }}," for lo, hi in ranges]
lines += ["};", ""]
out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"{out.name}: {len(decomp)} decompositions, {len(ranges)} mark ranges", file=sys.stderr)

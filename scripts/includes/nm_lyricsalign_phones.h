/*
 * nm_lyricsalign_phones.h - espeak-ng's IPA output as words and phones, and
 * the mapping of a phone onto the wav2vec2 phoneme vocabulary, for the
 * lyricsalign filter (nomercy-ffmpeg #126, "Phonemes: espeak-ng").
 *
 * The filter asks espeak_TextToPhonemes() for `espeakPHONEMES_IPA | ('_' << 8)`,
 * the library form of the CLI's `--ipa --sep=_` the prototype parsed, and
 * hands the joined clauses to nm_lp_parse_ipa(). The parsing and the five
 * mapping candidates are the prototype's (lyrics_eval.phonemes), measured
 * on the reference set: a phone that misses every candidate is dropped and
 * counted by the caller, never replaced by <unk>.
 *
 * Header-only, no espeak-ng and no FFmpeg: tests/unit/test_nm_lyricsalign_phones.c
 * checks it against a twelve-voice corpus the real espeak-ng produced.
 * The Unicode facts (precomposed Latin letters and the Mn/Cf ranges the
 * third candidate drops) come from nm_lyricsalign_unicode.inc, generated by
 * tools/lyricsalign-lab/make_unicode_inc.py.
 *
 * Memory: NM_LP_MALLOC / NM_LP_REALLOC / NM_LP_FREE, the C library unless the
 * includer says otherwise (af_lyricsalign.c points them at av_malloc).
 */
#ifndef NM_LYRICSALIGN_PHONES_H
#define NM_LYRICSALIGN_PHONES_H

#include <stddef.h>
#include <stdint.h>
#include <string.h>

#ifndef NM_LP_MALLOC
#include <stdlib.h>
#define NM_LP_MALLOC(n)     malloc(n)
#define NM_LP_REALLOC(p, n) realloc(p, n)
#define NM_LP_FREE(p)       free(p)
#endif

#include "nm_lyricsalign_unicode.inc"

typedef struct NMLpWord {
    char **phones;
    int n;
} NMLpWord;

/* ---------------------------------------------------------------------------
 * UTF-8
 * ------------------------------------------------------------------------- */

/* Decode one code point at p; *len is the bytes consumed. An ill-formed byte
 * is returned as itself (one byte), so nothing is ever skipped silently. */
static inline uint32_t nm_lp_utf8_decode(const unsigned char *p, int *len)
{
    uint32_t c = p[0];
    int need, i;

    if (c < 0x80) {
        *len = 1;
        return c;
    }
    if (c >= 0xC2 && c <= 0xDF)
        need = 1, c &= 0x1F;
    else if (c >= 0xE0 && c <= 0xEF)
        need = 2, c &= 0x0F;
    else if (c >= 0xF0 && c <= 0xF4)
        need = 3, c &= 0x07;
    else {
        *len = 1;
        return p[0];
    }
    for (i = 1; i <= need; i++) {
        if ((p[i] & 0xC0) != 0x80) {
            *len = 1;
            return p[0];
        }
        c = (c << 6) | (p[i] & 0x3F);
    }
    *len = need + 1;
    return c;
}

/* Encode c at out (at most 4 bytes); returns the byte count. */
static inline int nm_lp_utf8_encode(uint32_t c, char *out)
{
    if (c < 0x80) {
        out[0] = (char) c;
        return 1;
    }
    if (c < 0x800) {
        out[0] = (char) (0xC0 | (c >> 6));
        out[1] = (char) (0x80 | (c & 0x3F));
        return 2;
    }
    if (c < 0x10000) {
        out[0] = (char) (0xE0 | (c >> 12));
        out[1] = (char) (0x80 | ((c >> 6) & 0x3F));
        out[2] = (char) (0x80 | (c & 0x3F));
        return 3;
    }
    out[0] = (char) (0xF0 | (c >> 18));
    out[1] = (char) (0x80 | ((c >> 12) & 0x3F));
    out[2] = (char) (0x80 | ((c >> 6) & 0x3F));
    out[3] = (char) (0x80 | (c & 0x3F));
    return 4;
}

/* ---------------------------------------------------------------------------
 * Parsing
 * ------------------------------------------------------------------------- */

static inline int nm_lp_is_space(unsigned char c)
{
    return c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f' || c == '\v';
}

static inline int nm_lp_is_lower(unsigned char c)
{
    return c >= 'a' && c <= 'z';
}

/* Length of a language-switch marker "(xx)" or "(xx-yy)" starting at p, 0 if
 * p does not start one. espeak-ng writes these when a word is spoken in
 * another language; they are not phones. */
static inline int nm_lp_language_switch_len(const char *p)
{
    int i = 1, letters = 0;

    if (p[0] != '(')
        return 0;
    while (nm_lp_is_lower((unsigned char) p[i]))
        i++, letters++;
    if (letters < 2 || letters > 3)
        return 0;
    if (p[i] == '-') {
        int more = 0;
        i++;
        while (nm_lp_is_lower((unsigned char) p[i]))
            i++, more++;
        if (!more)
            return 0;
    }
    return p[i] == ')' ? i + 1 : 0;
}

static inline void nm_lp_free_words(NMLpWord *w, int n)
{
    if (!w)
        return;
    for (int i = 0; i < n; i++) {
        for (int j = 0; j < w[i].n; j++)
            NM_LP_FREE(w[i].phones[j]);
        NM_LP_FREE(w[i].phones);
    }
    NM_LP_FREE(w);
}

/* One phone from [p, end): the stress marks U+02C8 and U+02CC dropped. NULL
 * when nothing is left or memory ran out (*oom set). */
static inline char *nm_lp_phone(const char *p, const char *end, int *oom)
{
    char *out = (char *) NM_LP_MALLOC((size_t) (end - p) + 1);
    size_t n = 0;

    if (!out) {
        *oom = 1;
        return NULL;
    }
    while (p < end) {
        int len;
        uint32_t c = nm_lp_utf8_decode((const unsigned char *) p, &len);

        if (c != 0x02C8 && c != 0x02CC) {
            memcpy(out + n, p, (size_t) len);
            n += (size_t) len;
        }
        p += len;
    }
    if (!n) {
        NM_LP_FREE(out);
        return NULL;
    }
    out[n] = 0;
    return out;
}

/* espeak-ng IPA text -> words of phones. 0 on success, -1 out of memory. An
 * input with no phones gives *n_words = 0 and *words = NULL. */
static inline int nm_lp_parse_ipa(const char *ipa, NMLpWord **words, int *n_words)
{
    NMLpWord *out = NULL;
    int n = 0, cap = 0, oom = 0;
    const char *p = ipa;

    *words = NULL;
    *n_words = 0;
    while (*p) {
        const char *start, *q;
        NMLpWord w = { NULL, 0 };
        int wcap = 0;

        /* skip blanks and language-switch markers between words */
        for (;;) {
            int skip;
            if (nm_lp_is_space((unsigned char) *p)) {
                p++;
                continue;
            }
            skip = nm_lp_language_switch_len(p);
            if (skip) {
                p += skip;
                continue;
            }
            break;
        }
        if (!*p)
            break;
        start = p;
        while (*p && !nm_lp_is_space((unsigned char) *p) && !nm_lp_language_switch_len(p))
            p++;
        /* the word [start, p): phones separated by '_' */
        q = start;
        while (q <= p) {
            const char *sep = q;
            char *phone;

            while (sep < p && *sep != '_')
                sep++;
            phone = nm_lp_phone(q, sep, &oom);
            if (oom)
                goto fail;
            if (phone) {
                if (w.n == wcap) {
                    char **grown;
                    wcap = wcap ? wcap * 2 : 8;
                    grown = (char **) NM_LP_REALLOC(w.phones, sizeof(*grown) * (size_t) wcap);
                    if (!grown) {
                        NM_LP_FREE(phone);
                        goto fail_word;
                    }
                    w.phones = grown;
                }
                w.phones[w.n++] = phone;
            }
            q = sep + 1;
        }
        if (w.n) {
            if (n == cap) {
                NMLpWord *grown;
                cap = cap ? cap * 2 : 16;
                grown = (NMLpWord *) NM_LP_REALLOC(out, sizeof(*grown) * (size_t) cap);
                if (!grown)
                    goto fail_word;
                out = grown;
            }
            out[n++] = w;
        } else {
            NM_LP_FREE(w.phones);
        }
        continue;
fail_word:
        for (int j = 0; j < w.n; j++)
            NM_LP_FREE(w.phones[j]);
        NM_LP_FREE(w.phones);
        goto fail;
    }
    *words = out;
    *n_words = n;
    return 0;
fail:
    nm_lp_free_words(out, n);
    return -1;
}

/* ---------------------------------------------------------------------------
 * Mapping
 * ------------------------------------------------------------------------- */

static inline int nm_lp_is_mark(uint32_t c)
{
    if (c > 0xFFFF)
        return 0;
    for (size_t i = 0; i < sizeof(nm_lp_marks) / sizeof(nm_lp_marks[0]); i++)
        if (c >= nm_lp_marks[i].lo && c <= nm_lp_marks[i].hi)
            return 1;
    return 0;
}

/* The prototype's third candidate: Unicode NFD with categories Mn and Cf
 * dropped. Precomposed Latin letters give their base letter(s); combining
 * marks and format characters vanish. 0 on success, -1 if out is too small. */
static inline int nm_lp_strip_marks(const char *phone, char *out, size_t cap)
{
    const unsigned char *p = (const unsigned char *) phone;
    size_t n = 0;

    while (*p) {
        int len, k;
        uint32_t c = nm_lp_utf8_decode(p, &len);
        uint32_t emit[2] = { c, 0 };
        int n_emit = 1;

        p += len;
        if (c >= 0xC0 && c <= 0xFFFF) {
            for (size_t i = 0; i < sizeof(nm_lp_decomp) / sizeof(nm_lp_decomp[0]); i++) {
                if (nm_lp_decomp[i].cp == c) {
                    emit[0] = nm_lp_decomp[i].base[0];
                    emit[1] = nm_lp_decomp[i].base[1];
                    n_emit = emit[1] ? 2 : 1;
                    break;
                }
            }
        }
        for (k = 0; k < n_emit; k++) {
            char buf[4];
            int m;

            if (nm_lp_is_mark(emit[k]))
                continue;
            m = nm_lp_utf8_encode(emit[k], buf);
            if (n + (size_t) m + 1 > cap)
                return -1;
            memcpy(out + n, buf, (size_t) m);
            n += (size_t) m;
        }
    }
    if (n + 1 > cap)
        return -1;
    out[n] = 0;
    return 0;
}

static inline int nm_lp_find(const char *s, const char *const *vocab, int n_vocab)
{
    if (!s[0])
        return -1;
    for (int i = 0; i < n_vocab; i++)
        if (!strcmp(vocab[i], s))
            return i;
    return -1;
}

/* Phone -> vocabulary id, first hit wins: the phone; the nearest-neighbour
 * table; the phone with combining marks and format characters removed; that
 * without the length mark; its first code point. -1 when all five miss. */
static inline int nm_lp_map_phone(const char *phone, const char *const *vocab, int n_vocab)
{
    static const struct { const char *from, *to; } nearest[] = {
        { "\xCA\x8F", "\xCA\x8A" },             /* ʏ -> ʊ */
        { "\xC9\x92", "\xC9\x94" },             /* ɒ -> ɔ */
        { "\xC9\xB5", "\xC3\xB8" },             /* ɵ -> ø */
        { "\xCA\x89", "u" },                    /* ʉ -> u */
        { "\xC9\xA8", "\xC9\xAA" },             /* ɨ -> ɪ */
        { "\xC9\xAB", "l" },                    /* ɫ -> l */
        { "\xC9\xB1", "m" },                    /* ɱ -> m */
        { "\xCA\x8C\xCA\x8A", "a\xCA\x8A" },    /* ʌʊ -> aʊ (Dutch ou/au as espeak writes it) */
        { "\xC5\x93y", "\xC9\x94\xC3\xB8" },    /* œy -> ɔø (Dutch ui) */
    };
    char plain[64], shorter[64];
    int id, len;
    size_t n = 0;

    id = nm_lp_find(phone, vocab, n_vocab);
    if (id >= 0)
        return id;
    for (size_t i = 0; i < sizeof(nearest) / sizeof(nearest[0]); i++) {
        if (!strcmp(phone, nearest[i].from)) {
            id = nm_lp_find(nearest[i].to, vocab, n_vocab);
            if (id >= 0)
                return id;
            break;
        }
    }
    if (nm_lp_strip_marks(phone, plain, sizeof(plain)))
        return -1;
    id = nm_lp_find(plain, vocab, n_vocab);
    if (id >= 0)
        return id;
    /* without the length mark U+02D0 (CB 90) */
    for (const char *p = plain; *p;) {
        uint32_t c = nm_lp_utf8_decode((const unsigned char *) p, &len);
        if (c != 0x02D0) {
            memcpy(shorter + n, p, (size_t) len);
            n += (size_t) len;
        }
        p += len;
    }
    shorter[n] = 0;
    id = nm_lp_find(shorter, vocab, n_vocab);
    if (id >= 0)
        return id;
    /* the first code point of the stripped phone */
    if (plain[0]) {
        char first[5];
        nm_lp_utf8_decode((const unsigned char *) plain, &len);
        memcpy(first, plain, (size_t) len);
        first[len] = 0;
        return nm_lp_find(first, vocab, n_vocab);
    }
    return -1;
}

#endif /* NM_LYRICSALIGN_PHONES_H */

"""Turn jfk-alignment.json (the prototype's numbers on whisper.cpp's jfk.wav, see README.md here) into jfk_fixture.h,
plain C arrays the unit tests of nm_lyricsalign_align.h and nm_lyricsalign_phones.h compare against.

    python -I tests/unit/fixtures/jfk/make_fixture_h.py          (from the repository root)

Only the standard library and numpy; no torch. The .npy stays a file the test reads at run time (its 128-byte v1.0
header, '<f2', shape (550, 392)); this header only records its name and shape.
"""
import json
import sys
from pathlib import Path

import numpy as np

here = Path(__file__).resolve().parent
fix = json.loads((here / "jfk-alignment.json").read_text(encoding="utf-8"))
logp = np.load(here / "jfk-logprobs-f16.npy")
assert logp.shape == tuple(fix["emissions"]["shape"]) and logp.dtype == np.float16, (logp.shape, logp.dtype)

vit, line, words = fix["viterbi"], fix["line"], fix["words"]
tokens = fix["tokens"]
phones = [p for w in fix["espeak_ipa_words"] for p in w]
assert len(tokens) == len(vit["phone_first_frames"]) == len(vit["phone_posteriors"]) == len(phones)
assert sum(len(w["ids"]) for w in words) == len(tokens)


def c_int_array(name, values):
    return f"static const int {name}[{len(values)}] = {{ {', '.join(str(int(v)) for v in values)} }};"


def c_float_array(name, values):
    return f"static const float {name}[{len(values)}] = {{ {', '.join(f'{float(v):.4f}f' for v in values)} }};"


def c_str(s):
    return '"' + "".join(f"\\x{b:02x}" for b in s.encode("utf-8")) + '"'


out = [
    "/* Generated by make_fixture_h.py from jfk-alignment.json; do not edit. */",
    "#ifndef JFK_FIXTURE_H",
    "#define JFK_FIXTURE_H",
    "",
    f'#define JFK_LOGP_NPY "jfk-logprobs-f16.npy"',
    f"#define JFK_FRAMES {logp.shape[0]}",
    f"#define JFK_VOCAB {logp.shape[1]}",
    f"#define JFK_BLANK {int(vit['blank_id'])}",
    f"#define JFK_STAR_WEIGHT {float(vit['star_weight'])}",
    f"#define JFK_LINE_BLANK_PENALTY {float(vit['line_blank_penalty'])}f",
    f"#define JFK_STAR_FRAMES {int(vit['star_frames'])}",
    f"#define JFK_N_TOKENS {len(tokens)}",
    f"#define JFK_N_WORDS {len(words)}",
    f"#define JFK_START_SPIKE {float(line['start_spike'])}",
    f"#define JFK_END {float(line['end'])}",
    f"#define JFK_START_WRITTEN {float(line['start_written'])}",
    f"#define JFK_LEAD_IN {float(line['lead_in'])}",
    f"#define JFK_MEAN_SCORE {float(line['mean_score'])}",
    f'#define JFK_TEXT {c_str(fix["text"])}',
    f'#define JFK_LANGUAGE "{fix["language"]}"',
    "",
    c_int_array("JFK_TOKENS", tokens),
    c_int_array("JFK_FIRST_FRAMES", vit["phone_first_frames"]),
    c_float_array("JFK_POSTERIORS", vit["phone_posteriors"]),
    c_int_array("JFK_WORD_PHONES", [len(w["ids"]) for w in words]),
    "static const double JFK_WORD_STARTS[%d] = { %s };" % (len(words), ", ".join(f"{w['start']:.3f}" for w in words)),
    c_float_array("JFK_WORD_SCORES", [w["score"] for w in words]),
    "static const char *const JFK_WORD_TEXT[%d] = { %s };" % (len(words), ", ".join(c_str(w["text"]) for w in words)),
    "static const char *const JFK_PHONE_STRINGS[%d] = { %s };" % (len(phones), ", ".join(c_str(p) for p in phones)),
    "",
    "#endif /* JFK_FIXTURE_H */",
    "",
]
(here / "jfk_fixture.h").write_text("\n".join(out), encoding="utf-8", newline="\n")
print(f"jfk_fixture.h: {len(tokens)} tokens, {len(words)} words, {logp.shape[0]} frames", file=sys.stderr)
